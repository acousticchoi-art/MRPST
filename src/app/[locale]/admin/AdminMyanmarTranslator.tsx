function translate(root:HTMLElement){
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  const nodes:Text[]=[];
  while(walker.nextNode()) nodes.push(walker.currentNode as Text);
  for(const node of nodes){
    const parent=node.parentElement;
    if(!parent||parent.closest("script,style,textarea,[contenteditable=true],.notranslate,[data-no-translate]")) continue;
    const raw=node.nodeValue??"";
    const key=raw.trim();
    if(!key) continue;
    const translated=MY[key];
    if(translated) node.nodeValue=raw.replace(key,translated);
  }
  const elements=root.querySelectorAll<HTMLElement>("input[placeholder],textarea[placeholder],[title],[aria-label]");
  elements.forEach(el=>{
    for(const attr of ["placeholder","title","aria-label"]){
      const value=el.getAttribute(attr);
      if(value&&MY[value]) el.setAttribute(attr,MY[value]);
    }
  });
}

export default function AdminMyanmarTranslator({locale}:{locale:string}){
  useEffect(()=>{
    if(locale!=="my") return;
    const run=()=>translate(document.body);
    run();
    const observer=new MutationObserver(()=>run());
    observer.observe(document.body,{subtree:true,childList:true,characterData:true});
    return ()=>observer.disconnect();
  },[locale]);
  return null;
}
