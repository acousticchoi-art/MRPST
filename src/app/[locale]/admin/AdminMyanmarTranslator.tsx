function translateText(node:Text){
  const parent=node.parentElement;
  if(!parent||parent.closest("script,style,textarea,[contenteditable=true],.notranslate,[data-no-translate]")) return;
  const raw=node.nodeValue??"";
  const key=raw.trim();
  if(!key) return;
  const translated=MY[key];
  if(translated&&translated!==key) node.nodeValue=raw.replace(key,translated);
}

function translateElement(el:Element){
  if(el instanceof HTMLElement && !el.closest("script,style,textarea,[contenteditable=true],.notranslate,[data-no-translate]")){
    for(const attr of ["placeholder","title","aria-label"]){
      const value=el.getAttribute(attr);
      if(value&&MY[value]) el.setAttribute(attr,MY[value]);
    }
  }
  const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()) translateText(walker.currentNode as Text);
}

function translateNode(node:Node){
  if(node.nodeType===Node.TEXT_NODE){translateText(node as Text);return;}
  if(node.nodeType===Node.ELEMENT_NODE) translateElement(node as Element);
}


export default function AdminMyanmarTranslator({locale}:{locale:string}){
  useEffect(()=>{
    if(locale!=="my") return;
    const root=document.querySelector(".admin")??document.body;
    translateElement(root);
    let frame=0;
    const pending=new Set<Node>();
    const flush=()=>{
      frame=0;
      pending.forEach(translateNode);
      pending.clear();
    };
    const observer=new MutationObserver(records=>{
      for(const record of records){
        if(record.type==="childList"){
          record.addedNodes.forEach(node=>pending.add(node));
        }else if(record.type==="characterData"){
          pending.add(record.target);
        }else if(record.type==="attributes"){
          pending.add(record.target);
        }
      }
      if(!frame&&pending.size) frame=requestAnimationFrame(flush);
    });
    observer.observe(root,{
      subtree:true,
      childList:true,
      characterData:true,
      attributes:true,
      attributeFilter:["placeholder","title","aria-label"]
    });
    return ()=>{
      observer.disconnect();
      if(frame) cancelAnimationFrame(frame);
      pending.clear();
    };
  },[locale]);
  return null;
}
